"""Write tables.json + compliance.json into a C# static filler (Assets/Scripts/Editor/SuspensionTablesData.cs).
fields() is reused by sensitivity.py to produce runtime override files (-overrides) for perturbed inputs."""
import json, sys, os
def fields(t, c):
    K = c['rear']['Kkin']; rc_ = c['rear']['comp']; fr = c['front']
    f = dict(travel=t['travel'], frontCamberBody=t['front_camber_body'], frontBumpSteer=t['front_bumpsteer_toe'], frontTrackChange=t['front_track_change'],
        frontRcHeight=t['front_rc_height'], frontMotionRatio=t['front_motion_ratio'], rearMotionRatio=t['rear_motion_ratio'], steerGrid=t['front_steer_vs_rack'],
        frontCamberTravelSteer=[x for row in t['front_camber_travel_rack'] for x in row], rearCamberRollFraction=t['rear_camber_roll_fraction'], rearRcHeight=t['rear_rc_height'],
        rbCamOwn=K[0][0], rbCamOther=K[0][1], rbToeOwn=K[2][0], rbToeOther=K[2][1],
        rbToeFyOwn=rc_['Fy']['toeL'], rbToeFyOther=rc_['Fy']['toeR'], rbCamFyOwn=rc_['Fy']['camL'], rbCamFyOther=rc_['Fy']['camR'],
        rbToeFxOwn=rc_['Fx']['toeL'], rbToeFxOther=rc_['Fx']['toeR'], rbRcHeight=c['rear']['rc'], rbAntiLift=c['rear']['anti_lift'],
        fcToeFy=fr['Fy']['toe'], fcCamFy=fr['Fy']['camber'], fcToeFx=fr['Fx_brake']['toe'], fcCamFx=fr['Fx_brake']['camber'],
        fcToeFxD=fr['Fx_drive']['toe'], fcCamFxD=fr['Fx_drive']['camber'], fcToeFz=fr['Fz']['toe'], fcCamFz=fr['Fz']['camber'],
        fcAntiBrake=c['anti_brake_front'], fcAntiDrive=c['anti_drive_front'], fcJackPerFy=c['jack_front_per_Fy'])
    # joint reaction maps: force ON THE CAR BODY (left-corner frame x fwd, y left, z up) per unit tire load
    fj = []
    for ld in ('Fx_brake', 'Fx_drive', 'Fy', 'Fz'):
        for j in ('arm_front_bush', 'arm_rear_bush', 'tie_rod', 'top_mount'): fj += fr[ld]['body'][j]
        fj += fr[ld]['ball_joint']                                   # ball joint: force on the knuckle from the arm
    rj = []
    for ld in ('Fx', 'Fy', 'Fz'):
        for j in ('pivot_bush_L', 'pivot_bush_R', 'spring_damper_L', 'spring_damper_R'): rj += rc_[ld]['body'][j]
    f['fcJoint'] = fj; f['rbJoint'] = rj
    if 'front_toe_travel_rack' in t: f['rackGrid'] = t['rack']; f['frontToeTravelRack'] = [x for row in t['front_toe_travel_rack'] for x in row]
    sg = c['steer_geom']; f['kpU'] = sg['u']; f['kpRcp'] = sg['r_cp']; f['kpRwc'] = sg['r_wc']
    return f
def fmt(v): return "new float[]{" + ",".join(f"{x:.6g}f" for x in v) + "}" if isinstance(v, list) else f"{v:.6g}f"
def write_cs(t, c, cls, path):
    f = fields(t, c)
    body = "\n".join(f"        k.{n} = {fmt(v)};" for n, v in f.items())
    cs = f'''// AUTO-GENERATED by kinematics/export_unity.py from tables.json + compliance.json. Do not edit by hand.
// Source hardpoints: suspension_params.json (partly ESTIMATED). tie_rod_inner z re-derived for minimum bump steer.
public static class {cls}
{{
    public static void Fill(SuspensionTables k)
    {{
{body}
    }}
}}
'''
    open(path, 'w').write(cs)
    print("written", len(f), "fields; steerGrid ascending:", all(a < b for a, b in zip(t['front_steer_vs_rack'], t['front_steer_vs_rack'][1:])))

if __name__ == '__main__':
    E = '../unity/SciroccoSimDemo/Assets/Scripts/Editor/'
    write_cs(json.load(open('tables.json')), json.load(open('compliance.json')), 'SuspensionTablesData', E+'SuspensionTablesData.cs')
    pd_ = sys.argv[1] if len(sys.argv) > 1 else '../sensitivity/runs/proposed'
    if os.path.exists(pd_+'/tables.json'):
        tp = json.load(open(pd_+'/tables.json'))
        if 'front_toe_travel_rack' not in tp:   # stale proposed tables: carry the current steering grid so the runtime linkage works
            print('WARNING: proposed tables have no steering grid; using the current geometry grid'); m = json.load(open('tables.json'))
            for kk in ('rack', 'front_toe_travel_rack', 'front_steer_vs_rack', 'front_camber_travel_rack'): tp[kk] = m[kk]
        write_cs(tp, json.load(open(pd_+'/compliance.json')), 'SuspensionTablesDataProposed', E+'SuspensionTablesDataProposed.cs')
    else: print('WARNING: no proposed tables at', pd_)
